const P = (await import("@/lib/server-env")).PRODUCTION_SUPABASE;
const MONTH = process.argv[2] ?? "2026-09";
for (const k of ["SUPABASE_URL", "VITE_SUPABASE_URL"]) process.env[k] = P.SUPABASE_URL;
for (const k of ["SUPABASE_PUBLISHABLE_KEY", "VITE_SUPABASE_PUBLISHABLE_KEY"]) process.env[k] = P.SUPABASE_SERVICE_ROLE_KEY;
const { supabase } = await import("@/integrations/supabase/client");
const { fetchAllPages } = await import("@/lib/supabase-batch");
const [y, m] = MONTH.split("-").map(Number);
const last = new Date(Date.UTC(y!, m!, 0)).getUTCDate();
const sheets = await fetchAllPages<any>((a, b) => supabase.from("attendance_sheets" as never).select("id, unit_id, period_start, period_end").gte("period_end", `${MONTH}-01`).lte("period_end", `${MONTH}-${last}`).order("id").range(a, b));
const periods = new Map<string, { start: string; end: string }>();
for (const s of sheets) periods.set(s.unit_id, { start: s.period_start, end: s.period_end });
console.log("sheets", sheets.length, "units", periods.size);
const { computeDashboardUnitFinance } = await import("@/lib/dashboard-finance");
const { computePayrollUnitsTotals } = await import("@/lib/payroll-engine");
let t = Date.now();
const [f, p] = await Promise.all([computeDashboardUnitFinance(periods), computePayrollUnitsTotals(periods)]);
console.log("ms", Date.now() - t, f.size, p.size);
const out = [...periods.keys()].map((u) => ({ u, code: f.get(u)?.unit_code, s: periods.get(u)!.start, e: periods.get(u)!.end, inv: f.get(u)?.invoice_amount ?? null, fg: f.get(u)?.payroll_cost ?? null, fe: f.get(u)?.employer_contribution ?? null, pg: p.get(u)?.gross ?? null, pe: p.get(u)?.employer ?? null, pa: p.get(u)?.employerAll ?? null }));
(await import("fs")).writeFileSync(`/tmp/rls/admin-${MONTH}.json`, JSON.stringify(out));
process.exit(0);
